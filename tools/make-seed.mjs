// Builds supabase/seed.sql from the catalogue in assets/js/data.js.
//
//   node tools/make-seed.mjs
//
// The seed only adds rows that are missing ("on conflict do nothing"), so running it
// against a live database never overwrites changes the shop made in the admin panel.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFileSync(root + p, 'utf8');

// data.js and draw.js expect a browser `window`; give them a bare one
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(read('assets/js/draw.js'), sandbox);
vm.runInContext(read('assets/js/data.js'), sandbox);
const { CATEGORIES, PRODUCTS } = sandbox.window.MW_DATA;

const DEFAULT_SPECS = [['Material', 'Particle board'], ['Assembly', 'Easy assembly']];

const lit = (v) => {
  if (v == null) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;

const lines = [
  '-- Generated by tools/make-seed.mjs from assets/js/data.js. Do not edit by hand.',
  '-- Loads the original catalogue. Rows that already exist are left as they are.',
  '',
  'begin;',
  '',
];

lines.push('insert into public.categories (id, name, single, position, visible) values');
lines.push(CATEGORIES.map((c, i) => `  (${[c.id, c.name, c.single, (i + 1) * 10, true].map(lit).join(', ')})`).join(',\n'));
lines.push('on conflict (id) do nothing;', '');

lines.push('insert into public.products (id, category_id, name, series, quote, finish, h, d, w, mrp, price, components, specs, art_key, visible) values');
lines.push(PRODUCTS.map((p) => {
  const dims = p.dims || {};
  const components = (p.components || []).map((c) => ({ code: c.code, name: c.name, h: c.dims.h, d: c.dims.d, w: c.dims.w }));
  const specs = p.specs ? Object.entries(p.specs) : DEFAULT_SPECS;
  return `  (${[p.id, p.cat, p.name, p.series, p.quote, p.finish, dims.h, dims.d, dims.w, p.mrp, p.price].map(lit).join(', ')}, ${json(components)}, ${json(specs)}, ${lit(p.id)}, true)`;
}).join(',\n'));
lines.push('on conflict (id) do nothing;', '');

lines.push('-- tile pictures (only where none has been chosen yet)');
for (const c of CATEGORIES) {
  lines.push(`update public.categories set rep_product = ${lit(c.rep)} where id = ${lit(c.id)} and rep_product is null and photo_url is null;`);
}
lines.push('', 'commit;', '');

writeFileSync(root + 'supabase/seed.sql', lines.join('\n'));
console.log(`seed.sql: ${CATEGORIES.length} categories, ${PRODUCTS.length} products`);
